package ch.zhaw.it.pm4.discordmanagerbe.dto;

/**
 * Enumeration of Discord channel types.
 * Defines the different types of channels available in Discord.
 */
public enum ChannelType {
    /** Text channel for written messages */
    TEXT,
    /** Voice channel for audio communication */
    VOICE,
    /** Category channel for organizing other channels */
    CATEGORY
}